function redactItem(i) {
  if (!i || typeof i !== "object") return i;
  const o = {};
  for (const [k, v] of Object.entries(i)) if (!TRUST_FIELDS.includes(k) && k !== "verified") o[k] = v;
  if (i.verified && typeof i.verified === "object") {
    o.verified = { checked_at: i.verified.checked_at ?? null };
    if (i.verified.degraded) o.verified.degraded = true;
  } else o.verified = i.verified ?? null;
  o.trust_layer = "paid";
  return o;
}
